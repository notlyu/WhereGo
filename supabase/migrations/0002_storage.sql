-- ---------- Размер файла ----------
-- Для счётчика занятого места в настройках: на бесплатном тарифе это 1 ГБ
-- на всё, и при превышении Supabase отдаёт 402, переставая обслуживать не
-- только фото, но и ленту со входом. Расход должен быть виден заранее.
--
-- Держим в таблице, а не считаем по storage.objects: та закрыта, а обходить
-- это функцией с security definer ради счётчика — лишняя дыра.

alter table photos add column if not exists bytes int;

comment on column photos.bytes is 'Размер сжатого файла в байтах. Заполняется при загрузке.';
